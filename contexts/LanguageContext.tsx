interface LanguageContextType {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: any, defaultEn?: string, defaultAr?: string) => string;
  isRTL: boolean;
}

export const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export const LanguageProvider: React.FC<{ children: ReactNode }> = ({ children }) => {
  // Default to Arabic for this request
  const [language, setLanguage] = useState<Language>('ar'); 

  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
  }, [language]);

  const t = (key: any, defaultEn?: string, defaultAr?: string) => {
    const dict = translations[language];
    if (dict && (dict as any)[key]) {
      return (dict as any)[key] as string;
    }
    
    // Fallbacks
    if (language === 'ar' && defaultAr) return defaultAr;
    if (language === 'en' && defaultEn) return defaultEn;

    return key as string;
  };

  const isRTL = language === 'ar';

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, isRTL }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};